"""Read every PDF-extracted JSON page and preserve stage times, comments and key metrics.
No timezone is assigned: source pages do not label it. PDF page numbers are 1-based.
Run: python extract_service_timeline.py source.json output.txt
"""
import json,re,sys
A=json.load(open(sys.argv[1]));out=[]
for a in A:
 t=a['text'];n=a['page'];out.append(f'\nPAGE {n}\n')
 if 'Start Frac' in t:
  for l in t.splitlines():
   if re.search(r'Stage \d+ of|Start Frac|Perforation Depth|Stage Proppant|Clean Treatment Volume|Job Completion|Wellhead Rate|FracPumpTime',l):out.append(re.sub(r' +',' ',l).strip())
  if 'Frac Comments' in t:out.append(t[t.index('Frac Comments'):])
 else:
  # Keep all chart text; avoid meaningless whitespace generated by page layout.
  out.append(re.sub(r' +',' ',t))
open(sys.argv[2],'w').write('\n'.join(out))
